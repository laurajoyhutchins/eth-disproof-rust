"""Conditional support theorem for global weighted mode elimination.

The bound applies to the *actual* positive-weight domains generated by
mode_catalog, to every projected/partial factor assignment, and to the
literal paper schedule when the packing and shrinkage premises hold.
It is not a time bound on arbitrary vertex oracles, nor a total solver proof.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from math import isqrt
from collections.abc import Sequence

from non_exponential_sudoku.contraction.engine import paper_schedule_parameters
from non_exponential_sudoku.runtime.config import ContractorConfig
from reference.precision_envelope import paper_frame_envelopes


def ceil_sqrt(n: int) -> int:
    if type(n) is not int or n < 0:
        raise ValueError('nonnegative integer required')
    r = isqrt(n)
    return r if r * r == n else r + 1


def colored_partition_log2_ceiling(colors: int, precision: int) -> int:
    """For <= colors distinct modes of each weight w=1,...,p-1.

    Admissible beta have sum(w*beta_w,c) < p. The sum of coefficients of
    prod_{w>=1}(1-x**w)**(-colors) below degree p is < 2**(4 sqrt(K*p)).
    This follows from evaluating the nonnegative series at x=exp(-delta),
    -log(1-exp(-v)) expansion, sum(m^-2)<7/4 and ln(2)>2/3.
    Returns a conservative *integer exponent*, not an enumerated table.
    """
    if type(colors) is not int or colors < 0:
        raise ValueError('colors must be a nonnegative integer')
    if type(precision) is not int or precision < 1:
        raise ValueError('precision must be positive')
    return 4 * ceil_sqrt(colors * precision)


def exact_weighted_assignment_count(
    weights: Sequence[int], caps: Sequence[int], precision: int,
) -> int:
    """Independent small-instance generating-function reference.

    This counts finite bounded nonnegative multiplicity assignments using
    a polynomial DP, not the repository's DFS weighted_tuples enumerator.
    Intended for small fixtures, not an input-size-independent algorithm.
    """
    if len(weights) != len(caps) or type(precision) is not int or precision < 1:
        raise ValueError('invalid weighted-domain dimensions or precision')
    if any(type(w) is not int or w < 1 for w in weights):
        raise ValueError('weights must be positive integers')
    if any(type(c) is not int or c < 0 for c in caps):
        raise ValueError('caps must be nonnegative integers')
    totals = [1] + [0] * (precision - 1)
    for weight, cap in zip(weights, caps):
        new = [0] * precision
        for degree, count in enumerate(totals):
            if count:
                for b in range(min(cap, (precision - degree - 1) // weight) + 1):
                    new[degree + weight * b] += count
        totals = new
    return sum(totals)


@dataclass(frozen=True)
class PaperModeSupportEnvelope:
    """Conditional support bound for *one* paper frame's factor tables."""

    depth: int
    edges: int
    slots: int
    active_coordinates: int
    base_precision: int
    packet_count_ceiling: int
    colors_per_weight_ceiling: int
    color_precision_product_ceiling: int
    log2_support_ceiling: int


def center_color_precision_product(
    *, edges: int, packet_count: int, slots: int,
    active_coordinates: int, precision: int,
) -> int:
    """Uniform K(t)*p(t) bound for actual evaluated nonzero centers.

    If i=v2(t)<u then T=2**(i+1) y0 values per packet and
    p(t)=p+8*h*(L//2**i)+8*M*(a+1). The taper makes
    (P*T)*(8*h*L//2**i) == 16*P*h*L, independent of i.
    Taking T<=2**u in the remaining terms gives the bound below.
    """
    if any(type(v) is not int for v in (
        edges, packet_count, slots, active_coordinates, precision,
    )):
        raise ValueError('all inputs must be integers')
    if slots <= 0 or slots & (slots - 1):
        raise ValueError('slots must be a power of two')
    if active_coordinates < 1 or (slots.bit_length() - 1) < 2 * active_coordinates:
        raise ValueError('paper schedule requires a>=2u>=2')
    if edges < active_coordinates or precision < 1 or packet_count < 0:
        raise ValueError('an active nonnegative frame is required')
    if packet_count * slots > 3 * edges:
        raise ValueError('packet count violates the paper packing lemma')
    h = (3 * edges + active_coordinates - 1) // active_coordinates
    a = slots.bit_length() - 1
    return (packet_count * (1 << active_coordinates) *
            (precision + 8 * edges * (a + 1)) +
            16 * packet_count * h * slots)


def paper_global_mode_support_envelopes(
    config: ContractorConfig, *, edges: int, vertices: int,
) -> tuple[PaperModeSupportEnvelope, ...]:
    """Symbolic per-frame bound when actual paper packings are admitted.

    Each catalogued mode is indexed by a packet, y0, and b=w-1. Thus
    there are at most P*2**(i+1) modes of *each weight* w, and every
    retained factor row satisfies total weight < the center precision.
    """
    if config.schedule != 'paper':
        raise ValueError('literal paper schedule required')
    frames = paper_frame_envelopes(config, edges, vertices)
    lam = max(1, (config.s - 1).bit_length())
    result: list[PaperModeSupportEnvelope] = []
    for f in frames:
        if f.terminal:
            continue
        _, a, u, _ = paper_schedule_parameters(config.s, lam, f.depth)
        if f.slots != (1 << a):
            raise AssertionError('paper schedule and precision envelope differ')
        packets = 3 * f.edges // f.slots
        colors = packets * (1 << u)
        color_p = center_color_precision_product(
            edges=f.edges, packet_count=packets, slots=f.slots,
            active_coordinates=u, precision=f.precision,
        )
        result.append(PaperModeSupportEnvelope(
            depth=f.depth, edges=f.edges, slots=f.slots,
            active_coordinates=u, base_precision=f.precision,
            packet_count_ceiling=packets,
            colors_per_weight_ceiling=colors,
            color_precision_product_ceiling=color_p,
            log2_support_ceiling=4 * ceil_sqrt(color_p),
        ))
    return tuple(result)


def uniform_support_ratio_square_bound(lambda_bits: int) -> Fraction:
    """A purely symbolic uniform upper bound on K*p/s**2 at every depth.

    Assumes M0<=s, p0<=s, child shrinkage M_d<=(3/32)^d*s,
    and successful paper packet-count and precision bounds.
    The returned rational tends to zero as lambda_bits tends to infinity.
    Only O(log lambda_bits) small rational operations are needed.
    """
    if type(lambda_bits) is not int or lambda_bits < 1:
        raise ValueError('lambda_bits must be a positive integer')
    d = 0
    accumulated = 0
    rho = Fraction(1)
    ratio = Fraction(0)
    while True:
        u = lambda_bits // (131072 * (1 << d))
        if not u:
            return ratio
        accumulated += 2 * u
        # If u is enormous, substitute the weaker 2^-2*ceil(log2(lambda))
        # rather than allocating an astronomical denominator.
        capped_u = min(u, 2 * lambda_bits.bit_length())
        term = (3 * rho * (37 + 8 * (accumulated + 1)) / (1 << capped_u)
                + 192 * rho * rho / u)
        ratio = max(ratio, term)
        rho *= Fraction(3, 32)
        d += 1


@dataclass(frozen=True)
class UniformPairPackingWitness:
    """Compressed *mathematical* family, not an allocated Network or run.

    Take one distinguishable degree-one edge for each pair of full endpoint
    labels, repeated H times. Supply those endpoint labels to pack().
    Every ordered class then has exactly H edges; if H is a multiple of L,
    the resulting packing has exactly M/L fully occupied packets and
    exactly M/r ports per group/coordinate/side.
    """

    lambda_bits: int
    edges: int
    vertex_count: int
    max_actual_degree: int
    degree_hypothesis_ceiling: int
    full_pair_label_classes: int
    edges_per_class: int
    packet_slots: int
    packet_count: int
    group_side_port_load: int
    admitted_numeric_hypotheses: bool


def uniform_label_pair_paper_witness(lambda_bits: int) -> UniformPairPackingWitness:
    """Describe an explicitly supplied-label paper packing using O(log s) bits.

    This is a formula-level witness; it does NOT execute balanced_labels or
    allocate its exponentially many degree-one vertices. The claim depends
    on using the specified endpoint labels as the optional pack() input.
    """
    if type(lambda_bits) is not int or lambda_bits < 131072:
        raise ValueError('paper-active lambda >= 131072 required')
    r = 64
    u = lambda_bits // 131072
    a = 2 * u
    L = 1 << a
    D = r ** (2 * a)
    M = 1 << lambda_bits
    H, rem = divmod(M, D)
    if rem or H % L:
        raise ValueError('uniform class size must fill complete packets')
    # s=M=2**lambda; Delta=ceil(s**(9/10)) is bounded above by this
    # exact integer, requiring no floating-point exponentiation.
    delta_upper = 1 << ((9 * lambda_bits + 9) // 10)
    numerical = (M >= 2 * D * D * delta_upper and M >= L * D
                 and 2 * L <= delta_upper
                 and (M // L) * L <= 3 * M
                 and (M // r) * r <= 3 * M)
    return UniformPairPackingWitness(
        lambda_bits, M, 2 * M, 1, delta_upper, D, H,
        L, M // L, M // r, numerical,
    )
