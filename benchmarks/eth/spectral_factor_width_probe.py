"""Measure certified factor width of the ACTUAL swap/spectral construction.

Unlike benchmarks/eth/factor_width_obstruction.py, no measurements or
replacement polynomials are chosen by hand. Every center is generated by
construct_bounded_designs, including the exact auxiliary operator,
incidence-to-coordinate transfer and independently certified witnesses.

The finite-size parameter choices here are not the manuscript's literal
n-derived schedule. Conditional-expectations balancing is used except
where a case is explicitly labeled as the separate digit demonstration.
"""
from __future__ import annotations

from collections import Counter
from typing import Literal

from non_exponential_sudoku.eth.balance import BalanceLimits
from non_exponential_sudoku.eth.cnf import CNFFormula
from non_exponential_sudoku.eth.construction import (
    ConstructionLimits, ConstructedDesigns, ImplicitAuxiliaryDesign,
    construct_bounded_designs,
)
from non_exponential_sudoku.eth.design import certify_measurements
from non_exponential_sudoku.eth.factor_width import audit_factor_width
from non_exponential_sudoku.eth.parameters import audit_bounded_cnf
from non_exponential_sudoku.runtime.budget import CapacityError


def ring_formula(n: int, *, width: Literal[2, 3] = 2) -> CNFFormula:
    """A bounded-occurrence cyclic 2/3-CNF with every variable active."""
    if type(n) is not int or n < 4 or width not in (2, 3):
        raise ValueError('require n>=4 and 2<=width<=3')
    clauses = tuple(
        tuple((i + j) % n + 1 for j in range(width))
        for i in range(n)
    )
    return CNFFormula(n, clauses)


def _profile(
    formula: CNFFormula, construction: ConstructedDesigns,
    *, schedule: Literal['conditional', 'digits'],
) -> dict[str, object]:
    center_profiles: list[dict[str, object]] = []
    for center, design in construction.centers:
        # Deliberately re-certify from the generated replacements, never
        # infer support from clause incidence or unverified projector rows.
        certificate = certify_measurements(
            formula, construction.replacements, design, at=center)
        audit = audit_factor_width(certificate)
        center_profiles.append({
            'center': center,
            'measurement_rows': audit.measurement_rows,
            'factor_edges': len(audit.interaction_edges),
            'factor_scopes': audit.factor_scopes,
            'induced_scope_groups': audit.max_scope_groups,
            'max_dense_domain_bits': audit.max_domain_bits,
            'complete_group_graph': audit.complete_graph,
            'exact_treewidth_if_complete': audit.exact_treewidth_if_complete,
            'nontrivial_cross_group_factors': sum(
                len(scope) > 1 for scope in audit.factor_scopes),
        })
    paper = audit_bounded_cnf(formula)
    max_occurrences = max(Counter(
        abs(literal) for clause in formula.clauses for literal in clause
    ).values(), default=0)
    aux = construction.auxiliary
    if not isinstance(aux, ImplicitAuxiliaryDesign):
        raise TypeError('spectral-width probe requires the implicit auxiliary')
    return {
        'nvars': formula.nvars,
        'clauses': len(formula.clauses),
        'max_clause_width': max(map(len, formula.clauses), default=0),
        'max_variable_occurrences': max_occurrences,
        'r': aux.r, 'Q': aux.Q, 'R': aux.R,
        'schedule': schedule,
        'measurement_basis': aux.measurement_basis,
        'virtual_auxiliary_dimension': aux.dimension,
        'exceptional_basis_count': aux.exceptional_count,
        'label_multiplicity': construction.label_multiplicity,
        'max_measurement_rows': construction.max_measurement_rows,
        'balancing_lemma_hypotheses_met': (
            construction.balancing.lemma_hypotheses_met
            if construction.balancing else False),
        'balancing_lemma_bounds_met': (
            construction.balancing.lemma_bounds_met
            if construction.balancing else False),
        'paper_parameters_admitted': paper.admitted,
        'paper_parameter_failures': paper.failures,
        'centers': center_profiles,
    }


def probe() -> dict[str, object]:
    configurations: tuple[
        tuple[str, int, int, int, int, int, Literal['conditional', 'digits']], ...
    ] = (
        ('ring6-q2-r2', 6, 2, 2, 2, 2, 'conditional'),
        ('ring6-q2-r3', 6, 2, 3, 2, 2, 'conditional'),
        ('ring8-q2-r4', 8, 2, 4, 2, 2, 'conditional'),
        ('ring9-q3-r3', 9, 3, 3, 3, 2, 'conditional'),
        ('ring9-q3-r3-r3', 9, 3, 3, 3, 3, 'conditional'),
        ('ring9-q6-r2-digits', 9, 3, 2, 6, 1, 'digits'),
    )
    results: list[dict[str, object]] = []
    for label, n, width, r, Q, R, schedule in configurations:
        formula = ring_formula(n, width=width)
        try:
            design = construct_bounded_designs(
                formula, r=r, Q=Q, R=R, schedule=schedule,
                representation='implicit', measurement_basis='projector',
                limits=ConstructionLimits(
                    max_variables=32, max_clauses=64,
                    max_occurrences=64, max_measurement_rows=128,
                    max_implicit_points=12,
                ),
                balance_limits=BalanceLimits(
                    max_domain_size=32, max_indicator_work=2_000_000,
                ),
            )
        except (CapacityError, ValueError) as exc:
            results.append({'case': label, 'status': 'refused',
                            'reason': type(exc).__name__ + ': ' + str(exc)})
            continue
        results.append({
            'case': label,
            'status': 'certified',
            **_profile(formula, design, schedule=schedule),
        })
    return {
        'status': 'exact-finite-spectral-construction-width-probe',
        'note': 'toy r,Q,R, not literal paper schedule; explicit refusal preserved',
        'cases': results,
    }


def main() -> None:
    import json

    print(json.dumps(probe(), indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
