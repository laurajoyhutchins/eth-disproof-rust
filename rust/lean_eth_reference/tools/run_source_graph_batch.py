#!/usr/bin/env python3
"""Pin original Lean and source blobs, elaborate the executable Cmd tree, validate Rust.

The six golden tables are previously exported source artifacts, not generated by
this graph implementation. This runner never treats a partial source graph as
complete and preserves a detailed per-declaration refusal ledger.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
from export_compiled_batch import ensure_pinned, atomic_write
from extract_compiled_catalog import discover, blob_hash
from verify_source_graph import (validate_and_generate, parse_source_graph_json,
                                 parse_golden, rust_instr)
from source_graph_kernel_certificate import certificate_source

HERE=Path(__file__).resolve().parent
LEAN=HERE/'export_source_graph.lean'


def source(record:dict) -> str:
    assert re.fullmatch('[a-z0-9_-]{1,255}',record['id'])
    assert re.fullmatch('[0-9a-f]{40}',record['git_blob'])
    assert re.fullmatch(r'OAI\.Algorithms\.SubexponentialSAT(?:\.[A-Za-z_]\w*)+',record['module'])
    assert re.fullmatch(r'OAI\.Algorithms\.SubexponentialSAT(?:\.[A-Za-z_]\w*)+',record['fqn'])
    return (f'import {record["module"]}\n'+LEAN.read_text()+
            '\nset_option maxHeartbeats 2000000\n'+
            f'#export_original_source_graph {record["fqn"]} "{record["id"]}" "{record["git_blob"]}"\n')



def verify_original_linking_fixtures(a, pin: dict, catalog: dict) -> None:
    """Check real original ProgramLinking operations through the one compiler.

    These are source-derived sidecar programs, NOT declarations present in the
    pinned OpenAI Git tree. The original logSuccProgram is the finite callee.
    Each sidecar is independently materialized by Lean and compared with
    structurally exported, kernel-certified, generated Rust.
    """
    original = next((record for record in catalog['candidates']
                     if record['fqn'].endswith('SqrtLog.Setup.logSuccProgram')), None)
    if original is None:
        raise ValueError('missing source-pinned logSuccProgram for link fixtures')
    if blob_hash((a.upstream/original['file']).read_bytes()) != original['git_blob']:
        raise ValueError('linked fixture callee source Git blob mismatch')
    fqn=original['fqn']
    module=original['module']
    # The lean/Mathlib restore does not build original OpenAI modules.
    # Build only the one imported callee, not the whole six-program batch.
    built=subprocess.run(['lake','-K','maxJobs=2','build',module],
                         cwd=a.lake_root,capture_output=True,text=True,
                         timeout=a.timeout_seconds)
    if built.returncode:
        raise ValueError('original linking fixture module build failed: '+
                         built.stdout[-2500:]+built.stderr[-2500:])
    fixture_module='OAI.Algorithms.SubexponentialSAT.LinkCompilerFixture'
    definitions=f"""namespace {fixture_module}
noncomputable def lifted :=
  StructuredCalls.compiled
    (StructuredCalls.Cmd.call (ProgramLinking.liftProgram
      {fqn} (Fin.castAddEmb 1) (Fin.castAddEmb 1))) 0 0
noncomputable def linked :=
  StructuredCalls.compiled
    (StructuredCalls.Cmd.call (ProgramLinking.link {fqn} {fqn})) 0 0
noncomputable def linkedInto :=
  StructuredCalls.compiled
    (StructuredCalls.Cmd.call (ProgramLinking.linkInto {fqn} {fqn}
      (Fin.castAddEmb 1) (Fin.castAddEmb 1)
      (Fin.castAddEmb 1) (Fin.castAddEmb 1))) 0 0
-- Direct physical Program roots: there must be no extra call/return site.
noncomputable def liftedRoot :=
  ProgramLinking.liftProgram {fqn} (Fin.castAddEmb 1) (Fin.castAddEmb 1)
noncomputable def linkedRoot :=
  ProgramLinking.link {fqn} {fqn}
noncomputable def linkedIntoRoot :=
  ProgramLinking.linkInto {fqn} {fqn}
    (Fin.castAddEmb 1) (Fin.castAddEmb 1)
    (Fin.castAddEmb 1) (Fin.castAddEmb 1)
-- Source-level fixed repetition. The body is a real imported Lean program,
-- not a Rust-only synthesized table or semantic SAT shortcut.
noncomputable def repeatedRoot :=
  StructuredCalls.compiled
    (Nat.rec (StructuredCalls.Cmd.base .skip)
      (fun _ acc => StructuredCalls.Cmd.seq acc (StructuredCalls.Cmd.call {fqn}))
      4) 0 0
-- The source recursor is no longer at the root. It must be reduced through
-- named Lean definitions without expanding four physical copies.
noncomputable def namedRepeatCommand : StructuredCalls.Cmd 3 3 :=
  Nat.rec (StructuredCalls.Cmd.base .skip)
    (fun _ acc => StructuredCalls.Cmd.seq acc (StructuredCalls.Cmd.call {fqn}))
    4
noncomputable def namedRepeatAlias := namedRepeatCommand
noncomputable def namedRepeatRoot :=
  StructuredCalls.compiled namedRepeatAlias 0 0
-- Named physical-link aliases must not force a finite callee table.
noncomputable def namedLiftProgram := ProgramLinking.liftProgram
  {fqn} (Fin.castAddEmb 1) (Fin.castAddEmb 1)
noncomputable def namedLiftAlias := namedLiftProgram
noncomputable def namedLiftRoot := namedLiftAlias
end {fixture_module}
"""
    imports=(f'import {module}\n'
             'import OAI.Algorithms.SubexponentialSAT.ProgramLinking\n')
    dir=a.output_dir/'linking-fixtures'
    dir.mkdir(parents=True, exist_ok=True)
    gold=dir/'original-tables'
    gold.mkdir(exist_ok=True)
    rust=dir/'generated-rust'
    certs=dir/'kernel-certificates'
    certs.mkdir(exist_ok=True)
    gold_manifest={}
    accepted=[]
    supported=('lifted','linked','linkedInto',
               'liftedRoot','linkedRoot','linkedIntoRoot','repeatedRoot','namedRepeatRoot',
               'namedLiftRoot')
    selected=a.fixture_names or supported
    if not selected or any(name not in supported for name in selected):
        raise ValueError('unknown or empty original source fixture selection')
    for short in selected:
        fid='linked_fixture_'+short.lower()
        record={'id':fid,'fqn':fixture_module+'.'+short,
                'module':module,'git_blob':original['git_blob']}
        graph_source=(imports+LEAN.read_text()+'\n'+definitions+
                      '\nset_option maxHeartbeats 2000000\n'+
                      f'#export_original_source_graph {record["fqn"]} "{fid}" "{record["git_blob"]}"\n')
        table_source=(imports+(HERE/'export_source_program.lean').read_text()+
                      '\n'+definitions+'\nset_option maxHeartbeats 2000000\n'+
                      f'#export_original_program {record["fqn"]} "{fid}" "{record["git_blob"]}"\n')
        with tempfile.TemporaryDirectory(prefix='original-link-fixture-') as tmp:
            for suffix, program in (('graph',graph_source),('table',table_source)):
                src=Path(tmp)/(fid+'-'+suffix+'.lean')
                src.write_text(program, encoding='utf-8')
                check=subprocess.run(['lake','env','lean',str(src)],
                                     cwd=a.lake_root,capture_output=True,text=True,
                                     env={**os.environ,'ORIGINAL_MAX_LABELS':'4096'},
                                     timeout=a.timeout_seconds)
                if check.returncode:
                    raise ValueError(f'{fid} original Lean {suffix} export failed: '+
                                     check.stdout[-2500:]+check.stderr[-2500:])
                if suffix=='graph':
                    atomic_write(dir/(fid+'.json'),check.stdout)
                else:
                    raw=check.stdout.encode('ascii')
                    if not raw.startswith(f'PIN|{fid}|'.encode()) or not raw.endswith(
                            f'END|{fid}|'.encode()+raw.splitlines()[1].split(b'|')[4]+b'\n'):
                        raise ValueError(f'{fid} independent Lean table malformed')
                    (gold/(fid+'.table')).write_bytes(raw)
            graph=parse_source_graph_json((dir/(fid+'.json')).read_bytes())
            expected={'lifted':'lift','linked':'link','linkedInto':'link_into',
                      'liftedRoot':'lift','linkedRoot':'link',
                      'linkedIntoRoot':'link_into','namedLiftRoot':'lift'}.get(short)
            if short in ('repeatedRoot','namedRepeatRoot'):
                command=graph.get('command',{})
                if (graph.get('kind')!='original-structured-source-v1' or
                        command.get('kind')!='repeat' or command.get('count')!=4 or
                        command.get('body',{}).get('kind')!='call'):
                    raise ValueError(
                        f'{fid} original Nat.rec was not preserved as an exact repeat')
                if graph['abi']['labels']!=145:
                    raise ValueError(f'{fid} expected 145 physical source labels')
            elif short.endswith('Root'):
                if (graph['kind']!='original-linked-source-v1' or
                        graph.get('program',{}).get('kind')!=expected):
                    raise ValueError(
                        f'{fid} direct physical root did not preserve ProgramLinking.{expected}')
                expected_labels={'liftedRoot':36,'linkedRoot':72,'linkedIntoRoot':72,'namedLiftRoot':36}[short]
                if graph['abi']['labels']!=expected_labels:
                    raise ValueError(
                        f'{fid} unexpected physical labels: {graph["abi"]["labels"]}')
            else:
                command=graph['command']
                if (graph['kind']!='original-structured-source-v1' or
                        command.get('kind')!='call' or
                        command['program'].get('kind')!=expected):
                    raise ValueError(
                        f'{fid} source did not preserve ProgramLinking.{expected} as a graph node')
            table_bytes=(gold/(fid+'.table')).read_bytes()
            gold_manifest[fid]={'declaration':record['fqn'],
                                'source_blob':record['git_blob'],
                                'sha256':hashlib.sha256(table_bytes).hexdigest()}
            atomic_write(gold/'manifest.json',json.dumps(gold_manifest,sort_keys=True)+'\n')

            cert,cert_receipt=certificate_source(dir/(fid+'.json'),record)
            # The acceptance fixture itself is source-derived, so include
            # exactly its definition in the kernel witness before proving.
            cert=cert.replace(f'import {module}\n',
                              imports+definitions+'\n',1)
            cert_receipt['certificate_sha256']=hashlib.sha256(cert.encode()).hexdigest()
            cert_path=certs/(fid+'.lean')
            atomic_write(cert_path,cert)
            check=subprocess.run(['lake','env','lean',str(cert_path)],
                                 cwd=a.lake_root,capture_output=True,text=True,
                                 timeout=a.timeout_seconds)
            if check.returncode or check.stdout.strip():
                raise ValueError(f'{fid} original Lean kernel certificate failed: '+
                                 check.stdout[-2500:]+check.stderr[-2500:])
            cert_receipt['status']='LEAN_KERNEL_CERTIFIED_SOURCE_DERIVED_FIXTURE'
            cert_receipt['lean_version']=pin['lean']
            atomic_write(certs/(fid+'.receipt.json'),
                         json.dumps(cert_receipt,sort_keys=True,indent=2)+'\n')
            verified=validate_and_generate(dir/(fid+'.json'),gold,rust,
                                           a.rust_crate,not a.no_cargo)
            if verified['graph_sha256']!=cert_receipt['source_graph_sha256']:
                raise ValueError('fixture graph mutated between Lean and Rust verification')
            verified['fixture_kind']='source-derived (not original declaration)'
            verified['kernel_certificate_sha256']=cert_receipt['certificate_sha256']
            accepted.append(verified)
            atomic_write(dir/'report.json',
                         json.dumps({'kind':'source-derived-linking-acceptance',
                                     'source_callee':fqn, 'accepted':accepted},
                                    sort_keys=True,indent=2)+'\n')
            print('SOURCE_LINKING_FIXTURE_EXACT',fid,verified['physical_instructions_compared'],
                  flush=True)



def verify_receipt_native_build(a, record: dict, graph: Path,
                                certificate: Path, receipt: Path) -> dict:
    """Smoke the public receipt-driven CLI on one genuinely certified original.

    Do not substitute a locally fabricated kernel receipt: this is called
    only *after* the original Lean certificate has been kernel-checked and
    the independent table has matched the source graph.
    """
    with tempfile.TemporaryDirectory(prefix='original-native-receipt-') as scratch:
        output=Path(scratch)/'native'
        result=subprocess.run(
            ['cargo','run','--locked','--offline','--quiet',
             '--manifest-path',str(a.rust_crate/'Cargo.toml'),
             '--bin','original-source-build','--',
             str(graph),str(receipt),str(certificate),str(output)],
            capture_output=True,text=True,timeout=a.timeout_seconds)
        if result.returncode:
            raise ValueError('receipt-bound AOT native build failed: '+
                             result.stderr[-2500:])
        binary=output/'target/debug/original_lean_aot'
        if not binary.is_file():
            raise ValueError('receipt-bound native build produced no executable')
        report=json.loads((output/'build.receipt.json').read_text())
        golden=(a.golden_dir/(record['id']+'.table')).read_bytes()
        _, rows=parse_golden(golden,record['id'],record['git_blob'])
        if (report.get('status')!='GENERATED_AND_NATIVE_BUILT' or
                report.get('id')!=record['id'] or
                report.get('physical_labels')!=len(rows)):
            raise ValueError('native build receipt disagrees with original Lean table')
        for pc, instruction in enumerate(rows):
            check=subprocess.run([str(binary),'lookup',str(pc)],
                                 capture_output=True,text=True,timeout=15)
            if check.returncode or check.stdout.strip()!=rust_instr(instruction).removeprefix('Instr::'):
                raise ValueError(f'certified native binary differs at original label {pc}: '+
                                 check.stdout[-200:]+check.stderr[-200:])
        # Preserve a bounded proof artifact, not the generated Cargo target directory.
        atomic_write(a.output_dir/'receipt-native-build.json',
                     json.dumps(report,indent=2,sort_keys=True)+'\n')
        print('ORIGINAL_RECEIPT_NATIVE_BUILD_EXACT',record['id'],len(rows),flush=True)
        return report


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--upstream',required=True,type=Path)
    p.add_argument('--lake-root',required=True,type=Path)
    p.add_argument('--golden-dir',required=True,type=Path)
    p.add_argument('--output-dir',required=True,type=Path)
    p.add_argument('--rust-crate',required=True,type=Path)
    p.add_argument('--timeout-seconds',type=int,default=240)
    p.add_argument('--name-regex',default=r'SparseFrontierProgram\.(popIfPresentProgram|pushProgram)')
    p.add_argument('--limit',type=int,default=6)
    p.add_argument('--no-cargo',action='store_true')
    p.add_argument('--linking-fixtures',action='store_true')
    p.add_argument('--linking-fixtures-only',action='store_true')
    p.add_argument('--fixture-names',nargs='+',default=None,
                   help='source-derived compiler fixture names, defaults to all')
    a=p.parse_args()
    assert 5<=a.timeout_seconds<=1200 and 1<=a.limit<=6
    pin=ensure_pinned(a.upstream,a.lake_root)
    catalog=discover(a.upstream,True)
    if a.linking_fixtures_only:
        if not a.linking_fixtures:
            raise ValueError('--linking-fixtures-only requires --linking-fixtures')
        a.output_dir.mkdir(parents=True,exist_ok=True)
        verify_original_linking_fixtures(a,pin,catalog)
        return
    pattern=re.compile(a.name_regex)
    manifest=json.loads((a.golden_dir/'manifest.json').read_text())
    chosen=[x for x in catalog['candidates'] if pattern.search(x['fqn']) and x['id'] in manifest][:a.limit]
    if not chosen:raise SystemExit('no pinned original-source targets present in golden manifest')
    a.output_dir.mkdir(parents=True,exist_ok=True)
    # Never let a previous successful binary receipt survive a new attempt.
    (a.output_dir/'receipt-native-build.json').unlink(missing_ok=True)
    results=[];refused=[]
    def checkpoint():
        atomic_write(a.output_dir/'report.json',json.dumps({
            'kind':'original-Lean-structured-source-graph',
            'pins':pin,'accepted':results,'refused':refused,
            'selected':len(chosen),'attempted':len(results)+len(refused)
        },sort_keys=True,indent=2)+'\n')
    checkpoint()
    for record in chosen:
        source_path=a.upstream/record['file']
        if blob_hash(source_path.read_bytes())!=record['git_blob']:
            raise ValueError('source changed under immutable pinned Git checkout')
        try:
            with tempfile.TemporaryDirectory(prefix='original-graph-') as tmp:
                probe=Path(tmp)/'Export.lean'
                probe.write_text(source(record),encoding='utf8')
                build=subprocess.run(['lake','-K','maxJobs=2','build',record['module']],
                    cwd=a.lake_root,capture_output=True,text=True,timeout=a.timeout_seconds)
                if build.returncode:
                    raise ValueError('source module build failed: '+build.stderr[-1500:]+build.stdout[-1000:])
                result=subprocess.run(['lake','env','lean',str(probe)],cwd=a.lake_root,
                    env={**os.environ,'ORIGINAL_MAX_LABELS':'4096'},
                    capture_output=True,text=True,timeout=a.timeout_seconds)
                if result.returncode:
                    raise ValueError('source graph elaboration failed: '+result.stderr[-2500:]+result.stdout[-2000:])
                path=a.output_dir/(record['id']+'.json')
                atomic_write(path,result.stdout)
                # Fail closed before generating executable Rust: the candidate
                # instructions come from the *serialized graph*, not golden
                # tables. Lean proves full physical-code equality against its
                # independently imported original declaration.
                certificate, cert_receipt = certificate_source(path,record)
                certdir=a.output_dir/'certificates'
                certdir.mkdir(parents=True,exist_ok=True)
                certpath=certdir/(record['id']+'.lean')
                atomic_write(certpath,certificate)
                proof=subprocess.run(['lake','env','lean',str(certpath)],
                    cwd=a.lake_root,capture_output=True,text=True,
                    timeout=a.timeout_seconds)
                if proof.returncode or proof.stdout.strip():
                    atomic_write(certdir/(record['id']+'.diagnostics.txt'),
                        proof.stdout+'\n'+proof.stderr)
                    raise ValueError('Lean kernel source-graph certificate failed: '+
                        proof.stdout[:2400]+proof.stderr[:2400])
                cert_receipt['status']='LEAN_KERNEL_CERTIFIED_PHYSICAL_PROGRAM'
                cert_receipt['lean_version']=pin['lean']
                atomic_write(certdir/(record['id']+'.receipt.json'),
                    json.dumps(cert_receipt,sort_keys=True,indent=2)+'\n')
                accepted=validate_and_generate(path,a.golden_dir,a.output_dir/'rust',a.rust_crate,not a.no_cargo)
                if accepted['graph_sha256'] != cert_receipt['source_graph_sha256']:
                    raise ValueError('graph bytes changed between Lean certificate and Rust generation')
                accepted['kernel_certificate_sha256']=cert_receipt['certificate_sha256']
                accepted['kernel_certificate_status']=cert_receipt['status']
                if not results and not a.no_cargo:
                    native=verify_receipt_native_build(
                        a,record,path,certpath,certdir/(record['id']+'.receipt.json'))
                    # Hash the exact published JSON bytes, not a separately
                    # serialized representation of the in-memory receipt.
                    published=a.output_dir/'receipt-native-build.json'
                    accepted['receipt_native_build_sha256']=hashlib.sha256(
                        published.read_bytes()).hexdigest()
                results.append(accepted)
                print('ACCEPTED',record['id'],accepted['physical_instructions_compared'],flush=True)
        except (ValueError,subprocess.TimeoutExpired,RuntimeError,OSError) as exc:
            refused.append({'id':record['id'],'reason':type(exc).__name__,'detail':str(exc)[-5000:]})
            print('REFUSED',record['id'],type(exc).__name__,str(exc)[-300:],flush=True)
        checkpoint()
    if refused or len(results)!=len(chosen):
        raise SystemExit(f'source graph parity incomplete: accepted={len(results)}, refused={len(refused)}')
    if a.linking_fixtures:
        verify_original_linking_fixtures(a,pin,catalog)
    print(f'SOURCE_GRAPH_COMPLETE {len(results)} Lean-kernel-certified original-source graphs: all physical code + bounded Rust parity; native Rust equivalence is tested, not formally proved')

if __name__=='__main__':main()
